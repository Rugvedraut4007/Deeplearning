import zipfile
import os

zip_file = "/content/intel-image-classification.zip"

with zipfile.ZipFile(zip_file, 'r') as zip_ref:
    zip_ref.extractall("/content")

print("Dataset extracted successfully!")

import os

for root, dirs, files in os.walk("/content"):
    if "seg_train" in dirs:
        print("Training:", os.path.join(root, "seg_train"))

    if "seg_test" in dirs:
        print("Testing:", os.path.join(root, "seg_test"))

train_dir = "intel-image-classification.zip\Intel-Image-Classification\train"
test_dir = "intel-image-classification.zip\Intel-Image-Classification\test"

import tensorflow as tf
import numpy as np
import matplotlib.pyplot as plt

from tensorflow.keras import Sequential
from tensorflow.keras.layers import (
    Conv2D,
    MaxPooling2D,
    Flatten,
    Dense,
    Dropout
)

train_dataset = tf.keras.utils.image_dataset_from_directory(
    train_dir,
    image_size=(150, 150),
    batch_size=32,
    shuffle=True
)

test_dataset = tf.keras.utils.image_dataset_from_directory(
    test_dir,
    image_size=(150, 150),
    batch_size=32,
    shuffle=False
)

class_names = train_dataset.class_names

print("Classes:")
for i, name in enumerate(class_names):
    print(i, ":", name)

plt.figure(figsize=(10, 10))

for images, labels in train_dataset.take(1):
    for i in range(9):
        ax = plt.subplot(3, 3, i + 1)

        plt.imshow(images[i].numpy().astype("uint8"))
        plt.title(class_names[labels[i]])
        plt.axis("off")

plt.show()

normalization_layer = tf.keras.layers.Rescaling(1./255)

train_dataset = train_dataset.map(
    lambda x, y: (normalization_layer(x), y)
)

test_dataset = test_dataset.map(
    lambda x, y: (normalization_layer(x), y)
)

model = Sequential([

    # First Convolution Layer
    Conv2D(
        32,
        (3, 3),
        activation='relu',
        input_shape=(150, 150, 3)
    ),

    # Reduce image size
    MaxPooling2D((2, 2)),


    # Second Convolution Layer
    Conv2D(
        64,
        (3, 3),
        activation='relu'
    ),

    MaxPooling2D((2, 2)),


    # Third Convolution Layer
    Conv2D(
        128,
        (3, 3),
        activation='relu'
    ),

    MaxPooling2D((2, 2)),


    # Convert 2D feature maps to 1D
    Flatten(),


    # Fully Connected Layer
    Dense(
        128,
        activation='relu'
    ),


    # Prevent overfitting
    Dropout(0.5),


    # Output layer
    Dense(
        6,
        activation='softmax'
    )
])

model.summary()

model.compile(
    optimizer='adam',
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

history = model.fit(
    train_dataset,
    epochs=10,
    validation_data=test_dataset
)

import tensorflow as tf

print(tf.config.list_physical_devices('GPU'))

test_loss, test_accuracy = model.evaluate(test_dataset)

print("Test Loss:", test_loss)
print("Test Accuracy:", test_accuracy)
print("Test Accuracy (%):", test_accuracy * 100)

plt.figure(figsize=(8, 5))

plt.plot(history.history['accuracy'])
plt.plot(history.history['val_accuracy'])

plt.title("CNN Accuracy")
plt.xlabel("Epoch")
plt.ylabel("Accuracy")

plt.legend(["Training Accuracy", "Validation Accuracy"])

plt.show()

plt.figure(figsize=(8, 5))

plt.plot(history.history['loss'])
plt.plot(history.history['val_loss'])

plt.title("CNN Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")

plt.legend(["Training Loss", "Validation Loss"])

plt.show()

